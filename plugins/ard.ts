/** Canonical ARD path first, predecessor second. Same bytes at both (see the header comment). */
export const ARD_OUTPUT_PATHS = ['.well-known/ard.json', '.well-known/ai-catalog.json']

export function ardPlugin(options: Options): Plugin {
  let clientOutDir: string
  let isSSRBuild = false
  let ran = false
  const host = stripSlash(options.hostname)

  return {
    name: 'ard-plugin',
    configResolved(config) {
      isSSRBuild = !!config.build.ssr
      const resolvedOutDir = config.build.outDir ? path.resolve(config.build.outDir) : path.resolve('dist')
      clientOutDir = resolvedOutDir.endsWith(`${path.sep}client`) ? resolvedOutDir : path.join(resolvedOutDir, 'client')
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (!req.url) return next()
        const url = req.url.split('?')[0]
        if (!ARD_OUTPUT_PATHS.includes(url.replace(/^\//, ''))) return next()

        res.setHeader('Content-Type', 'application/json; charset=utf-8')
        // Registries fetch this cross-origin from the browser, so it has to be readable by anyone.
        res.setHeader('Access-Control-Allow-Origin', '*')
        return void res.end(buildAiCatalog(host, options.defaultLocale))
      })
    },
    async closeBundle() {
      if (isSSRBuild) return
      if (ran) return
      ran = true

      const content = buildAiCatalog(host, options.defaultLocale)
      await Promise.all(
        ARD_OUTPUT_PATHS.map(async (rel) => {
          const out = path.join(clientOutDir, rel)
          await fs.mkdir(path.dirname(out), { recursive: true })
          await fs.writeFile(out, content, 'utf8')
        })
      )
    },
  }
}
