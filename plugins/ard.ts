/**
 * Emits the ARD (Agentic Resource Discovery) capability manifest so registries can index
 * what this origin offers to agents *before* invoking anything.
 *
 * Spec: ARD v0.91 (github.com/ards-project/ard-spec), schema
 * `spec/schemas/ai-catalog.schema.json` ("AICatalogManifest").
 *
 * Files emitted (all under `dist/client`):
 *   /.well-known/ard.json          canonical ARD path (spec section 5.1)
 *   /.well-known/ai-catalog.json   predecessor path, same bytes
 *
 * WHY BOTH PATHS: ARD section 5.1 makes `/.well-known/ard.json` the one path a conformant
 * consumer MUST fetch, and demotes `/.well-known/ai-catalog.json` to a predecessor that
 * consumers MAY consult - "a publisher on the predecessor path SHOULD move to ard.json".
 * Publishing only the predecessor risks not being found at all. But the older path is what
 * already-deployed crawlers look for, and one document satisfies both schemas at once:
 * `AICatalogManifest` requires `specVersion` + `entries`, and `ArdManifest` requires only
 * `entries` while leaving other top-level members open. So we serve identical bytes at both
 * and stay conformant either way, at the cost of one extra small file.
 *
 * Everything is derived at build time from `lib/developers.ts` and the `hostname` option
 * (CI passes a per-deploy SITE_URL, so preview deploys advertise themselves, not vocdoni.io),
 * which is the same anti-drift rule `plugins/well-known.ts` follows.
 *
 * NOTE: the `Content-Type: application/json` and `Access-Control-Allow-Origin: *` headers
 * these files need on Netlify come from `_headers`, which is generated by
 * `plugins/well-known.ts`. The dev middleware below sets them directly.
 */

interface Options {
  hostname: string
  /** Locale used for the raw-markdown docs URL, which is emitted per locale by plugins/docs-markdown.ts. */
  defaultLocale: string
}

const stripSlash = (s: string) => s.replace(/\/+$/, '')

/**
 * Only "1.0" is accepted by the manifest schema's `specVersion` enum.
 */
export const AI_CATALOG_SPEC_VERSION = '1.0'

/**
 * The `<publisher>` segment of every `urn:air:` identifier. Deliberately hardcoded rather
 * than derived from `hostname`, for three reasons the spec is explicit about:
 *
 *  1. A URN is *identity*, not location. The naming guide (Scenario C) says an owner of a
 *     real FQDN must use it "even when developing and running locally", so "the URN remains
 *     completely identical between their local development, staging, and production
 *     catalogs". Deriving it from SITE_URL would mint a different identity for the same
 *     logical resource on every preview deploy, breaking the stable primary key registries
 *     index on. The per-deploy host still varies - it belongs in `url`, which is location.
 *  2. The `<publisher>` segment is the authority anchor: registries extract it and
 *     cross-reference it against DNS/DID attestations. Only vocdoni.io is verifiable.
 *  3. The identifier pattern (`^urn:air:[a-zA-Z0-9.-]+(:[a-zA-Z0-9._-]+)+$`) has no room for
 *     a port, so a `http://localhost:3000` dev hostname could not produce a valid URN, and
 *     the naming guide names `localhost` an outright anti-pattern.
 */
export const URN_PUBLISHER = 'vocdoni.io'

const urn = (namespace: string, name: string) => `urn:air:${URN_PUBLISHER}:${namespace}:${name}`

// --- pure builders (unit-tested) --------------------------------------------

export interface CatalogEntry {
  identifier: string
  displayName: string
  /** IANA media type of the artifact at `url`. */
  type: string
  url: string
  description: string
  tags: string[]
  /** Registries build their semantic index from these; the schema caps the array at 2-5. */
  representativeQueries: string[]
}

export interface AiCatalogManifest {
  specVersion: string
  host: {
    displayName: string
    documentationUrl: string
    logoUrl: string
  }
  entries: CatalogEntry[]
}

