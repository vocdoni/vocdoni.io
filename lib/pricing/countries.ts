/** A country's name in the given language, from the browser's own data; the code when it has none. */
export const countryName = (code: string, locale: string): string => {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? code
  } catch {
    return code
  }
}

/** Every country as { code, name }, sorted by name in the given language. */
export const countryOptions = (locale: string): { code: string; name: string }[] => {
  const names = new Intl.DisplayNames([locale], { type: 'region' })
  return COUNTRY_CODES.map((code) => ({ code, name: names.of(code) ?? code })).sort((a, b) =>
    a.name.localeCompare(b.name, locale)
  )
}

/**
 * The country the dropdown starts on, from the page language. The browser's own region is no use here:
 * many visitors in Spain browse in en-US. Spain covers the languages most of them read the site in.
 */
const LOCALE_COUNTRY: Record<string, string> = {
  de: 'DE',
  el: 'GR',
  fr: 'FR',
  hi: 'IN',
  it: 'IT',
  pt: 'PT',
  'pt-br': 'BR',
}

export const defaultCountry = (locale: string): string => LOCALE_COUNTRY[locale.toLowerCase()] ?? 'ES'
